"""Write patches/car_rescale.patch: the other cars' per-car handling values
moved by the same proportion as the Hornet's.

The Hornet (car 0) has DUSA's values (patches hornet_yaw_gain,
hornet_rear_stiffness, wheelspin_thresholds). DUSA has no counterparts for
CCE's other cars, so each of their values keeps its CCE ratio to the
Hornet's CCE value: new = CCE value x (Hornet new / Hornet CCE).

usage: car_rescale.py   (reads extracted/cce/DAYTONA/RACE.BIN)
"""
import struct

ORIG = 'extracted/cce/DAYTONA/RACE.BIN'
BASE = 0x06028000
CARS = 14

GAINS = 0x0604D1CC       # per car: rotation gain words (+0x16C, +0x16E)
STIFFNESS = 0x0604D2A0   # per car: front, rear lateral stiffness (16.16 longs)
THRESHOLDS = 0x0604D310  # per car: wheelspin threshold words, gears 1-4

HORNET_GAIN = (0x3A0, 0x52F)          # CCE, DUSA converted
HORNET_REAR = (0x2BC0000, 0x3200000)
HORNET_THRESHOLDS = ((36175, 26869, 20971, 23162), (36175, 26869, 20480, 21114))


def main():
    d = open(ORIG, 'rb').read()
    word = lambda a: struct.unpack_from('>H', d, a - BASE)[0]
    long_ = lambda a: struct.unpack_from('>I', d, a - BASE)[0]
    out = [line.rstrip() for line in HEADER.strip().splitlines()]
    for car in range(1, CARS):
        a = GAINS + car * 4
        old = [word(a), word(a + 2)]
        new = [round(v * HORNET_GAIN[1] / HORNET_GAIN[0]) for v in old]
        out.append(f'DAYTONA/RACE.BIN {a:08X} {BASE:08X} {old[0]:04x}{old[1]:04x} {new[0]:04x}{new[1]:04x}'
                   f'   # car {car} rotation gains')
    for car in range(1, CARS):
        a = STIFFNESS + car * 8 + 4
        old = long_(a)
        new = round(old * HORNET_REAR[1] / HORNET_REAR[0])
        out.append(f'DAYTONA/RACE.BIN {a:08X} {BASE:08X} {old:08x} {new:08x}'
                   f'   # car {car} rear stiffness {old / 65536:g} -> {new / 65536:.1f}')
    for car in range(1, CARS):
        a = THRESHOLDS + car * 8
        old = [word(a + 2 * g) for g in range(4)]
        new = [round(v * h1 / h0) for v, h0, h1 in zip(old, *HORNET_THRESHOLDS)]
        if new != old:
            out.append(f'DAYTONA/RACE.BIN {a:08X} {BASE:08X} {"".join(f"{v:04x}" for v in old)} '
                       f'{"".join(f"{v:04x}" for v in new)}   # car {car} wheelspin thresholds')
    open('patches/car_rescale.patch', 'w').write('\n'.join(out) + '\n')
    print(f'{len(out)} lines -> patches/car_rescale.patch')


HEADER = """
# Cars 1-13: per-car handling values moved by the Hornet's proportion
# (generated by tools/car_rescale.py). The Hornet has DUSA's values; DUSA
# has no counterparts for the other cars, so each keeps its CCE ratio to the
# Hornet: new = CCE value x (Hornet DUSA-converted / Hornet CCE).
#   rotation gains (0604D1CC -> +0x16C/+0x16E)  x 0x52F / 0x3A0 = 1.430
#   rear stiffness (0604D2A4 -> +0x150)          x 800 / 700     = 1.143
#   wheelspin thresholds (0604D310 -> +0x1B2)    per gear, x DUSA / CCE
#                                                (all cars share CCE's row)
"""

if __name__ == '__main__':
    main()
